"""SeekAuth - end-to-end verification of the check number (checknum).

Runs the full chain on a **real mcpHex** (captured from an actual FateArk request):
decrypt `vanilla.mcp` -> extract the salts -> compute the check number,
and compare it against the output of the Go reference implementation `noahs-ark`.

This step exercises the whole anti-cheat chain, which is more convincing than a unit test alone.
"""

from __future__ import annotations

import contextlib
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

with contextlib.suppress(Exception):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

MCPHEX_FILE = Path(r"E:\fateark\recon\mcphex.txt")
GO_REF = Path(r"E:\fateark\recon\checknum_ground_truth.json")


def _load_mcphex() -> str | None:
    if not MCPHEX_FILE.exists():
        return None
    txt = MCPHEX_FILE.read_text(encoding="utf-8").strip()
    return txt or None


pytestmark = pytest.mark.skipif(
    _load_mcphex() is None,
    reason="missing recon/mcphex.txt (a real mcpHex sample)",
)


def test_mcp_decrypts_to_valid_pyc() -> None:
    """Decrypting the MCP must yield valid Python 2.7 bytecode."""
    from seek_auth.checknum import decrypt_mcp

    mcp_hex = _load_mcphex()
    assert mcp_hex
    repaired = decrypt_mcp(bytes.fromhex(mcp_hex))

    # Python 2.7 magic number
    assert repaired[:4] == b"\x03\xf3\x0d\x0a", f"wrong magic: {repaired[:4].hex()}"
    assert len(repaired) > 5000, f"repaired payload too short: {len(repaired)}"
    print(f"  decrypt ok: {len(bytes.fromhex(mcp_hex))} -> {len(repaired)} bytes")


def test_salts_extracted() -> None:
    """Both salts must be extractable from the bytecode, matching the CalcCheckNum pattern."""
    from seek_auth.checknum import decrypt_mcp, extract_salts

    mcp_hex = _load_mcphex()
    assert mcp_hex
    repaired = decrypt_mcp(bytes.fromhex(mcp_hex))
    salts = extract_salts(repaired)

    assert salts.s1, "s1 is empty"
    assert salts.s2, "s2 is empty"
    # Salts are short ASCII strings; the length varies by mcp version (5/11/13 seen in practice)
    assert 1 <= len(salts.s1) <= 32, f"s1 length out of range: {len(salts.s1)}"
    assert 1 <= len(salts.s2) <= 32, f"s2 length out of range: {len(salts.s2)}"
    assert all(32 <= ord(c) < 127 for c in salts.s1 + salts.s2), "salt has non-ASCII chars"

    # Compare against the known authoritative values (expected salts for this same mcpHex)
    print(f"  salts: s1={salts.s1!r} (len={len(salts.s1)}) s2={salts.s2!r} (len={len(salts.s2)})")


def test_checknum_matches_go_reference() -> None:
    """The check number output must match the Go reference implementation exactly.

    The ground truth on the Go side is generated by `noahs-ark/diag/checknum_dump.go`.
    """
    from seek_auth.checknum import generate_transfer_check_num

    if not GO_REF.exists():
        pytest.skip(f"missing Go ground truth {GO_REF} (run noahs-ark/diag/checknum_dump.go)")

    gt = json.loads(GO_REF.read_text(encoding="utf-8"))
    for case in gt["cases"]:
        got = generate_transfer_check_num(
            case["data"],
            engine_version=case["engine_version"],
            patch_version=case["patch_version"],
            is_pc=case.get("is_pc", False),
        )
        want = case["expected"]
        assert got == want, (
            f"case {case['name']} mismatch:\n  got ={got}\n  want={want}"
        )
        print(f"  [PASS] {case['name']}")


def test_checknum_output_shape() -> None:
    """The output must be an 8-element array with correctly typed fields."""
    from seek_auth.checknum import generate_transfer_check_num

    mcp_hex = _load_mcphex()
    assert mcp_hex
    data = json.dumps([mcp_hex, "AbCdEf1234", -158913789949])
    out = generate_transfer_check_num(
        data, engine_version="3.6.5.281774", patch_version="3.6.56.288487"
    )
    arr = json.loads(out)

    assert isinstance(arr, list) and len(arr) == 8, f"wrong element count: {len(arr)}"
    valm, sign, flag, memcheck, pkgname, pkgsign, ver, tmps_num = arr
    assert isinstance(valm, str) and len(valm) == 32, f"valM is not a 32-char md5: {valm!r}"
    assert isinstance(sign, str) and len(sign) == 32, f"sign is not a 32-char md5: {sign!r}"
    assert flag is False, "element 3 should be false"
    assert memcheck == [], "element 4 should be an empty array"
    assert pkgname == "" and pkgsign == "", "pkgname/pkgsign should be empty for a genuine build"
    assert ver == 3, "element 7 should be 3"
    assert isinstance(tmps_num, str) and len(tmps_num) == 32
    print(f"  valM={valm} sign={sign[:16]}... tmpsNum={tmps_num[:16]}...")


def test_checknum_is_deterministic() -> None:
    """The same input must produce the same output (the check number has no randomness)."""
    from seek_auth.checknum import generate_transfer_check_num

    mcp_hex = _load_mcphex()
    assert mcp_hex
    data = json.dumps([mcp_hex, "ZzZzZz99", 12345])
    kw = {"engine_version": "3.6.5.281774", "patch_version": "3.6.56.288487"}
    a = generate_transfer_check_num(data, **kw)
    b = generate_transfer_check_num(data, **kw)
    assert a == b


def test_checknum_rejects_bad_input() -> None:
    """Invalid input must raise CheckNumError, never crash or return garbage."""
    from seek_auth.checknum import CheckNumError, generate_transfer_check_num

    kw = {"engine_version": "1", "patch_version": "2"}
    for bad in ("not json", "{}", "[]", '["a"]', '["zz","v",1]'):
        with pytest.raises(CheckNumError):
            generate_transfer_check_num(bad, **kw)


def test_checknum_pc_vs_android_differ() -> None:
    """PC and Android use different tmps, so the results must differ."""
    from seek_auth.checknum import generate_transfer_check_num

    mcp_hex = _load_mcphex()
    assert mcp_hex
    data = json.dumps([mcp_hex, "Qq12345678", 999])
    kw = {"engine_version": "3.6.5.281774", "patch_version": "3.6.56.288487"}
    android = generate_transfer_check_num(data, is_pc=False, **kw)
    pc = generate_transfer_check_num(data, is_pc=True, **kw)
    assert android != pc
