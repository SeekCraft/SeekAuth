"""Verify the Python rotor machine matches the Go reference implementation byte for byte.

Compared against `recon/rotor_ground_truth.txt` (generated by `noahs-ark/diag/rotor_dump.go`).
The rotor machine is the first step of decrypting `vanilla.mcp`; any deviation makes the
check digits come out wrong.
"""

from __future__ import annotations

import contextlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

with contextlib.suppress(Exception):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

from seek_auth.rotor import Rotor  # noqa: E402

GT = Path(r"E:\fateark\recon\rotor_ground_truth.txt")

# Key material identical to unmcpk/main.go
_ASDF_DN = "j2h56ogodh3sk"
_ASDF_DT = "=dziaq;"
_ASDF_DF = '|`o=5v7!"-276'


def build_key() -> str:
    return (
        _ASDF_DN * 4
        + (_ASDF_DT + _ASDF_DN + _ASDF_DF) * 5
        + "$@"
        + _ASDF_DT * 7
        + _ASDF_DF * 2
        + "&]`"
    )


def load_gt() -> dict[str, str]:
    out: dict[str, str] = {}
    for line in GT.read_text(encoding="utf-8").splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def main() -> int:
    gt = load_gt()
    key = build_key()
    failures: list[str] = []

    def check(name: str, got: str, want: str) -> None:
        ok = got == want
        mark = "PASS" if ok else "FAIL"
        if ok:
            # Byte counts only for pure hex values; other values (e.g. key_len) are shown as-is
            try:
                detail = f"{len(bytes.fromhex(got))} bytes"
            except ValueError:
                detail = got
        else:
            failures.append(name)
            detail = _diff_detail(got, want)
        print(f"  [{mark}] {name}  {detail}")

    def _diff_detail(got: str, want: str) -> str:
        """Locate the first differing byte: it shows whether the key or the rotor logic broke."""
        try:
            gb, wb = bytes.fromhex(got), bytes.fromhex(want)
        except ValueError:
            return f"got={got!r} want={want!r}"
        n = min(len(gb), len(wb))
        pos = next((i for i in range(n) if gb[i] != wb[i]), n)
        if pos >= n and len(gb) != len(wb):
            return f"length differs: got={len(gb)} want={len(wb)}"
        if pos >= n:
            return "identical content (should not get here)"
        return f"first difference @ byte {pos}: got={gb[pos]:02x} want={wb[pos]:02x}"

    print("=== Key material ===")
    check("key_len", str(len(key)), gt["key_len"])
    check("key_hex", key.encode().hex(), gt["key_hex"])

    print("\n=== Rotor E region (0..255) ===")
    seq = bytearray(range(256))
    Rotor(6, key).e_region(seq, True)
    check("e_region_0_255", seq.hex(), gt["e_region_0_255"])

    print("\n=== Rotor D region (wrap-around) ===")
    dec = bytearray(bytes.fromhex(gt["e_region_0_255"]))
    Rotor(6, key).d_region(dec, True)
    check("d_region_roundtrip", dec.hex(), gt["d_region_roundtrip"])

    print("\n=== Odd-length sample ===")
    sample = b"Seek-Auth rotor verification sample 0123456789"
    enc = bytearray(sample)
    Rotor(6, key).e_region(enc, True)
    check("e_region_sample", enc.hex(), gt["e_region_sample"])

    dec2 = bytearray(bytes.fromhex(gt["e_region_sample"]))
    Rotor(6, key).d_region(dec2, True)
    check("d_region_sample", dec2.hex(), gt["d_region_sample"])

    print("\n=== Self-consistency ===")
    # Any data must round-trip E->D
    rnd = bytes(range(200, 256)) * 3
    a = bytearray(rnd)
    Rotor(6, key).e_region(a, True)
    b = bytearray(a)
    Rotor(6, key).d_region(b, True)
    ok = bytes(b) == rnd
    print(f"  [{'PASS' if ok else 'FAIL'}] E->D self-consistent ({len(rnd)} bytes)")
    if not ok:
        failures.append("self-consistency")

    print()
    if failures:
        print(f"result: {len(failures)} failed -> {failures}")
        return 1
    print("result: the rotor matches the Go reference exactly (OK)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
